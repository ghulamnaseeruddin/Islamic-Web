// Makes supabase/seed_library.sql from library-data.json.
// Run:  npm run seed:library
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const data = JSON.parse(readFileSync(join(here, "library-data.json"), "utf8"));

const q = (v) => (v == null ? "null" : "'" + String(v).replace(/'/g, "''") + "'");
const lines = [];
lines.push("-- Library seed (generated by supabase/tools/generate-library-seed.mjs). Safe to run more than once.");
lines.push("-- Files are links to the original library. Nothing is copied or hosted by this app.");
lines.push("");

for (const s of data.sections) {
  const parent = s.parent ? `(select id from public.library_sections where slug = ${q(s.parent)})` : "null";
  lines.push(
    `insert into public.library_sections (slug, parent_id, title, title_ur, sort_order, app_path, note, is_hidden)\n` +
      `values (${q(s.slug)}, ${parent}, ${q(s.title)}, ${q(s.title_ur)}, ${s.sort}, ${q(s.app_path)}, ${q(s.note)}, ${s.is_hidden ? "true" : "false"})\n` +
      `on conflict (slug) do update set title = excluded.title, title_ur = excluded.title_ur, sort_order = excluded.sort_order, app_path = excluded.app_path, note = excluded.note;`,
  );
}
lines.push("");

for (const s of data.sections) {
  if (!s.books.length) continue;
  lines.push(`-- ${s.title}`);
  s.books.forEach((b, i) => {
    const files = JSON.stringify(b.files).replace(/'/g, "''");
    lines.push(
      `insert into public.library_books (section_id, title, files, app_path, sort_order)\n` +
        `values ((select id from public.library_sections where slug = ${q(s.slug)}), ${q(b.title)}, '${files}'::jsonb, ${q(b.app_path ?? null)}, ${i + 1})\n` +
        `on conflict (section_id, title) do update set files = excluded.files, app_path = excluded.app_path, sort_order = excluded.sort_order;`,
    );
  });
  lines.push("");
}

const out = join(here, "..", "seed_library.sql");
writeFileSync(out, lines.join("\n"));
const books = data.sections.reduce((n, s) => n + s.books.length, 0);
console.log(`Wrote ${out}: ${data.sections.length} sections, ${books} books`);
